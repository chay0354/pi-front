/**
 * One-off importer for Figma-generated illustration layers (category tiles, 2701 logo).
 *
 * Usage: node scripts/import-figma-layers.mjs <generated.tsx> <outName>
 *
 * - Downloads every `${assetPathPrefix}/<file>` asset into src/assets/figma/<outName>/
 * - Rewrites the TSX into plain JSX that styles DOM nodes through `tw()`
 *   (src/figma/tw.js) instead of Tailwind classes.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [, , inputPath, outName] = process.argv;
if (!inputPath || !outName) {
  console.error('Usage: node scripts/import-figma-layers.mjs <generated.tsx> <outName>');
  process.exit(1);
}

let src = await fs.readFile(inputPath, 'utf8');
const cut = src.indexOf('SUPER CRITICAL');
if (cut > 0) src = src.slice(0, cut);

const prefixMatch = src.match(/const assetPathPrefix = "([^"]+)";/);
if (!prefixMatch) throw new Error('assetPathPrefix not found');
const prefix = prefixMatch[1];

const assetDir = path.join(root, 'src', 'assets', 'figma', outName);
await fs.mkdir(assetDir, {recursive: true});

const assetRe = /^const (\w+) = `\$\{assetPathPrefix\}\/([^`]+)`;$/gm;
const assets = [...src.matchAll(assetRe)].map(m => ({name: m[1], file: m[2]}));

async function download({file}) {
  const dest = path.join(assetDir, file);
  try {
    const st = await fs.stat(dest);
    if (st.size > 0) return;
  } catch {}
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(`${prefix}/${file}`);
    if (res.ok) {
      await fs.writeFile(dest, Buffer.from(await res.arrayBuffer()));
      return;
    }
    await new Promise(r => setTimeout(r, 500 * (attempt + 1)));
  }
  throw new Error(`Failed to download ${file}`);
}

const queue = [...assets];
await Promise.all(
  Array.from({length: 8}, async () => {
    while (queue.length) await download(queue.shift());
  }),
);

const imports = assets
  .map(a => `import ${a.name} from '../../assets/figma/${outName}/${a.file}';`)
  .join('\n');

let body = src
  .replace(/^const assetPathPrefix = .*$/m, '')
  .replace(assetRe, '')
  .replace(/^type \w+ = \{[\s\S]*?^\};\n/gm, '')
  .replace(/\}: \{ className\?: string \}\)/g, '})')
  .replace(/\}: \w+Props\)/g, '})')
  .replace(/\s(?:id|data-node-id|data-name)=(?:"[^"]*"|\{[^}]*\})/g, '');

// DOM elements only: components keep their `className` prop and forward it.
body = body.replace(/<([a-z][a-z0-9]*)\b([^<>]*?)>/g, (tag, name, attrs) => {
  let out = attrs;
  let styleExpr = null;
  out = out.replace(/\sclassName=(\{(?:[^{}]|\{[^{}]*\})*\}|"[^"]*")/, (_, v) => {
    styleExpr = v.startsWith('{') ? v.slice(1, -1) : v;
    return '';
  });
  if (styleExpr == null) return tag;
  const inline = out.match(/\sstyle=\{\{((?:[^{}]|\{[^{}]*\})*)\}\}/);
  if (inline) {
    out = out.replace(inline[0], '');
    return `<${name} style={{...tw(${styleExpr}), ${inline[1].trim()}}}${out}>`;
  }
  return `<${name} style={tw(${styleExpr})}${out}>`;
});

body = body.replace(/^export default function/m, 'export function');
body = body.replace(/^function /gm, 'export function ');
body = body.replace(/\n{3,}/g, '\n\n').trim();

const header = `/* Generated by scripts/import-figma-layers.mjs from Figma — do not edit by hand. */
import {tw} from '../../figma/tw';
${imports}
`;

const outDir = path.join(root, 'src', 'components', 'figma');
await fs.mkdir(outDir, {recursive: true});
const outFile = path.join(outDir, `${outName}.generated.jsx`);
await fs.writeFile(outFile, `${header}\n${body}\n`, 'utf8');
console.log(`Wrote ${path.relative(root, outFile)} with ${assets.length} assets`);
